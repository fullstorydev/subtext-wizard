#!/usr/bin/env node
// Regenerates src/installPages/pages.generated.ts from the marketing site's
// install pages, which are the source of truth for install instructions.
//
//   node scripts/sync-install-pages.mjs                  # fetch from production
//   node scripts/sync-install-pages.mjs --from-dir DIR   # render content/install/*.txt from a site checkout
//
// Fails loudly instead of writing a snapshot that looks fine but isn't.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_URL = 'https://subtext.fullstory.com';
const APP_URL = 'https://app.fullstory.com';
const STEPS = ['capture', 'csp', 'identify', 'integrations', 'privacy'];
// Has to pass the edge function's org id check; swapped back to a placeholder below.
const FAKE_ORG = 'o-WIZARD0-na1';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'installPages', 'pages.generated.ts');

// Same block syntax as the site's scripts/lib/install-txt.ts, rendered for a
// known org with the page-to-page navigation dropped.
function renderTemplate(src) {
  return src
    .replace(/\{\{\^ORG\}\}[\s\S]*?\{\{\/ORG\}\}/g, '')
    .replace(/\{\{#ORG\}\}([\s\S]*?)\{\{\/ORG\}\}/g, '$1')
    .replaceAll('{{SITE_URL}}', SITE_URL)
    .replaceAll('{{APP_URL}}', APP_URL);
}

// Until the site serves ?embed=1, strip "## Next" here so the wizard, not the
// page, decides what runs after each step.
function stripNavigation(text) {
  return text.replace(/\n## Next\n[\s\S]*$/, '\n');
}

async function fetchPage(step) {
  const url = `${SITE_URL}/install/${step}.txt/${FAKE_ORG}?embed=1`;
  const res = await fetch(url, { redirect: 'manual' });
  if (res.status !== 200) throw new Error(`${url} returned ${res.status}`);
  return (await res.text()).replaceAll(FAKE_ORG, '{{ORG_ID}}');
}

function check(step, text) {
  const problems = [];
  if (text.length < 300) problems.push(`only ${text.length} chars`);
  const leftover = text.match(/\{\{(?!ORG_ID\}\})[^}]*\}\}/g);
  if (leftover) problems.push(`unfilled placeholders: ${[...new Set(leftover)].join(', ')}`);
  if (/^## Next/m.test(text)) problems.push('still has a "## Next" section');
  if (step === 'capture' && !/_fs_script/.test(text)) problems.push('snippet is missing _fs_script');
  if (step === 'capture' && !text.includes("'{{ORG_ID}}'")) problems.push('snippet org id is not templated');
  if (problems.length) throw new Error(`${step}: ${problems.join('; ')}`);
}

const dirFlag = process.argv.indexOf('--from-dir');
const fromDir = dirFlag === -1 ? null : process.argv[dirFlag + 1];

const pages = {};
for (const step of STEPS) {
  const raw = fromDir
    ? renderTemplate(fs.readFileSync(path.join(fromDir, `${step}.txt`), 'utf8'))
    : await fetchPage(step);
  pages[step] = stripNavigation(raw).replace(/\n{3,}/g, '\n\n').trim() + '\n';
  check(step, pages[step]);
}

const body = STEPS.map((s) => `  ${s}: ${JSON.stringify(pages[s])},`).join('\n');
const out = `// Generated by scripts/sync-install-pages.mjs from ${SITE_URL}/install. Don't edit by hand.
import type { InstallStep } from './steps.js';

export const INSTALL_PAGES: Record<InstallStep, string> = {
${body}
};
`;

const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (prev === out) {
  console.log('Install pages unchanged.');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
